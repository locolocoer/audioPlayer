const dictionaries: Record<Lang, Dict> = { zh, en }

function getInitialLang(): Lang {
  try {
    const saved = localStorage.getItem('lang')
    if (saved === 'zh' || saved === 'en') return saved
  } catch { /* ignore */ }
  return 'zh'
}

interface I18nState {
  lang: Lang
  setLang: (lang: Lang) => void
}

function syncLangToMain(lang: Lang): void {
  try {
    if (typeof window !== 'undefined' && window.api?.app?.setLang) {
      window.api.app.setLang(lang).catch(() => {})
    }
  } catch { /* ignore */ }
}

export const useI18nStore = create<I18nState>((set) => ({
  lang: getInitialLang(),
  setLang: (lang) => {
    try { localStorage.setItem('lang', lang) } catch { /* ignore */ }
    set({ lang })
    syncLangToMain(lang)
  }
}))

// 桌面歌词等独立窗口：接收主进程广播的语言变更，只更新本窗口，不回调主进程避免循环
export function applyLangFromMain(lang: string): void {
  if (lang !== 'zh' && lang !== 'en') return
  try { localStorage.setItem('lang', lang) } catch { /* ignore */ }
  useI18nStore.setState({ lang })
}

syncLangToMain(getInitialLang())

export function t(key: string, vars?: Record<string, string | number>): string {
  const lang = useI18nStore.getState().lang
  const dict = dictionaries[lang]
  let text = dict[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v))
    }
  }
  return text
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  useI18nStore((s) => s.lang)
  return t
}
